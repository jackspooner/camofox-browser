// Disposable direct sessions and browser profiles; only the installed binary cache is shared.
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, symlinkSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createServer } from 'node:http';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import express from 'express';
import { firefox } from 'playwright-core';
import { Supervisor } from '../../lib/platform/supervisor.js';
import { installViewer } from '../../lib/platform/viewer.js';
import { installPlatformRoutes } from '../../lib/platform/routes.js';
import { loadPlatformConfig } from '../../lib/config.js';
import { workerJson } from '../../lib/platform/worker-launcher.js';
const exec = promisify(execFile), cache = resolve(process.argv[2] || '');
assert(process.argv[2], 'Pass the installed browser cache');
const stateDir = mkdtempSync(join(tmpdir(), 'cf-transfer-live-'));
symlinkSync(cache, join(stateDir, 'cache'));
const config = { ...loadPlatformConfig(), stateDir }, supervisor = new Supervisor(config, {});
const fixture = createServer((_req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<!doctype html><title>Transfer fixture</title><h1>Transfer acceptance</h1><input id="draft" value="unsaved draft"><script>document.cookie="fixture_login=retained; SameSite=Lax";localStorage.setItem("fixture","retained");window.retainedMemory="unchanged"</script>'); });
await new Promise(r => fixture.listen(0, '127.0.0.1', r));
const app = express(); app.use(express.json());
const server = createServer(app); await new Promise(r => server.listen(0, '127.0.0.1', r)); config.port = server.address().port;
const viewer = installViewer(app, server, supervisor, config);
installPlatformRoutes(app, supervisor, config, viewer);
app.use((e, _req, res, _next) => res.status(e.statusCode || 500).json({ error: e.message, code: e.code }));
let browser;
try {
  const profile = supervisor.store.createProfile('Transfer acceptance');
  const session = supervisor.store.createSession(profile.id, 'Transfer acceptance', 'transfer-test');
  await supervisor.resume(session.id, 'transfer-test');
  const w = supervisor.workers.get(session.id);
  const created = await workerJson(w.socket, supervisor.config.workerKey, 'POST', '/tabs', { userId: session.id, sessionKey: 'default', url: `http://127.0.0.1:${fixture.address().port}` });
  const read = async () => (await workerJson(w.socket, supervisor.config.workerKey, 'POST', `/tabs/${created.tabId}/evaluate`, { userId: session.id, expression: '({cookie:document.cookie,storage:localStorage.getItem("fixture"),memory:window.retainedMemory,draft:document.querySelector("#draft").value})' })).result;
  const before = await read();
  await viewer.watch(session.id, 'transfer-test', true);
  const originalViewer = w.viewer, pid = w.viewer.desktop.child.pid;
  const copied = await exec('/usr/bin/python3', ['tests/platform/viewer-transfer-ui.py', String(pid)], { timeout: 30000 });
  const url = copied.stdout.trim(); assert(url.startsWith(`http://127.0.0.1:${config.port}/viewer#`));
  assert(w.viewer === originalViewer); assert(w.viewer.desktop);
  const official = join(cache, 'camoufox/browsers/official');
  const binary = join(official, readdirSync(official).find(name => name.startsWith('156.0.1-beta.36-')), 'camoufox-bin');
  browser = await firefox.launch({ executablePath: binary, headless: true });
  const firstContext = await browser.newContext(), first = await firstContext.newPage();
  await first.goto(url);
  await first.waitForFunction(() => document.querySelector('#status').textContent === 'Watching · agent can work');
  assert(w.viewer === originalViewer); assert.equal(w.viewer.desktop, null); assert.equal(w.humanControl, false);
  assert.deepEqual(await read(), before);
  console.log('PASS desktop-to-browser: native Copy URL, same worker, tab, cookie, localStorage, JS memory and draft');
  await first.getByRole('button', { name: 'Take control', exact: true }).click();
  await first.waitForFunction(() => document.querySelector('#status').textContent.startsWith('You control'));
  await first.getByRole('button', { name: 'Stop', exact: true }).click();
  await first.waitForFunction(() => document.querySelector('#operation').textContent === 'Automation paused');
  await first.getByRole('button', { name: 'Create new viewer URL', exact: true }).click();
  await first.waitForFunction(() => !!document.querySelector('#transfer-url').value);
  const nextUrl = await first.getByRole('textbox', { name: 'New viewer URL', exact: true }).inputValue();
  // Exercise the standard browser clipboard path without reading unrelated clipboard contents.
  await first.getByRole('button', { name: 'Copy URL', exact: true }).click();
  await first.waitForFunction(() => document.querySelector('#transfer-status').textContent === 'URL copied');
  const secondContext = await browser.newContext(), second = await secondContext.newPage();
  await second.goto(nextUrl);
  await second.waitForFunction(() => document.querySelector('#status').textContent.startsWith('You control'));
  await first.waitForFunction(() => document.querySelector('#status').textContent === 'Viewer moved to another browser.');
  await first.close();
  assert(w.viewer === originalViewer); assert(w.humanControl); assert(supervisor.store.session(session.id).automationPaused);
  assert.deepEqual(await read(), before);
  console.log('PASS browser-to-browser: old viewer moved notice, stale unload fenced, human control and automation pause retained');
  await second.getByRole('button', { name: 'Return to agent', exact: true }).click();
  await second.waitForFunction(() => document.querySelector('#status').textContent === 'Watching · agent can work');
  await second.getByRole('button', { name: 'Create new viewer URL', exact: true }).click();
  await second.waitForFunction(() => !!document.querySelector('#transfer-url').value);
  // Recover from a failed transfer by issuing another link in the still-working viewer.
  const retryUrl = await second.getByRole('textbox', { name: 'New viewer URL', exact: true }).inputValue();
  const abandoned = await (await browser.newContext()).newPage();
  await abandoned.route('**/viewer/app.js', route => route.abort());
  await abandoned.goto(retryUrl); await abandoned.close();
  assert(w.viewer === originalViewer);
  await second.getByRole('button', { name: 'Create new viewer URL', exact: true }).click();
  await second.waitForFunction(previous => document.querySelector('#transfer-url').value && document.querySelector('#transfer-url').value !== previous, retryUrl);
  await second.getByRole('button', { name: 'Close', exact: true }).click();
  await second.waitForFunction(() => document.querySelector('#status').textContent === 'Viewer closed');
  await originalViewer.closing;
  assert(w.viewer === null);
  console.log('PASS failed replacement leaves original usable; regenerate, return control and close work');
  // Source integration must tolerate a running gateway that still serves its
  // pre-transfer shell while app.js is read from the updated checkout on disk.
  const legacyLink = await viewer(session.id, 'transfer-test');
  const legacy = await (await browser.newContext()).newPage(), errors = [];
  legacy.on('pageerror', error => errors.push(error.message));
  await legacy.route(/\/viewer$/, async route => {
    const response = await route.fetch();
    const html = (await response.text()).replace(/<button id="transfer"[^>]*>[^<]*<\/button>/, '').replace(/<section id="transfer-panel"[\s\S]*?<\/section>/, '');
    await route.fulfill({ response, body: html });
  });
  await legacy.goto(legacyLink.url);
  await legacy.waitForFunction(() => document.querySelector('#status').textContent.startsWith('You control'));
  assert.deepEqual(errors, []);
  assert.equal(await legacy.getByRole('button', { name: 'Create new viewer URL', exact: true }).count(), 0);
  const legacyViewer = w.viewer;
  await legacy.getByRole('button', { name: 'Close', exact: true }).click();
  await legacy.waitForFunction(() => document.querySelector('#status').textContent === 'Viewer closed');
  await legacyViewer.closing;
  console.log('PASS updated client remains compatible with the pre-transfer viewer shell');
} finally {
  await browser?.close(); await supervisor.close();
  server.closeAllConnections(); await new Promise(r => server.close(r));
  fixture.closeAllConnections(); await new Promise(r => fixture.close(r));
  rmSync(stateDir, { recursive: true, force: true });
}
